export function DataTable({ columns, rows, statusColumn }) {
  const [message, setMessage] = useState('');

  const runCellAction = (cell) => {
    const label = String(cell);
    if (/download|pdf|excel/i.test(label)) {
      downloadTextFile(`${label.replace(/\s+/g, '-').toLowerCase()}.txt`, `${label}\nGenerated by MTPG & RIHS portal placeholder.`);
      setMessage(`${label} downloaded.`);
    } else {
      setMessage(`${label} action completed.`);
    }
  };

  return (
    <>
      {message && <div className="ems-action-message">{message}</div>}
      <div className="ems-table-shell">
        <table className="ems-data-table">
          <thead>
            <tr>{columns.map((column) => <th key={column}>{column}</th>)}</tr>
          </thead>
          <tbody>
            {rows.map((row, rowIndex) => (
              <tr key={`${rowIndex}-${row[0]}`}>
                {row.map((cell, cellIndex) => {
                  const actionCell = /download|review/i.test(String(cell));
                  return (
                    <td className={cellIndex === statusColumn ? 'ems-status-cell' : actionCell ? 'ems-action-cell' : undefined} key={`${cellIndex}-${cell}`}>
                      {cellIndex === statusColumn ? (
                        <StatusBadge status={cell} />
                      ) : actionCell ? (
                        <button className="ems-table-action" type="button" onClick={() => runCellAction(cell)}>{cell}</button>
                      ) : cell}
                    </td>
                  );
                })}
              </tr>
            ))}
          </tbody>
        </table>
      </div>
    </>
  );
}

export function FormField({ label, name, value, onChange, options, type = 'text', required, placeholder }) {
  return (
    <label className="ems-form-field">
      <span>{label}{required ? ' *' : ''}</span>
      {options ? (
        <select name={name} value={value} onChange={onChange} required={required}>
          <option value="">Select {label}</option>
          {options.map((option) => <option key={option} value={option}>{option}</option>)}
        </select>
      ) : (
        <input name={name} type={type} value={value} onChange={onChange} required={required} placeholder={placeholder || label} />
      )}
    </label>
  );
}

export function ValidatedForm({ fields, initialValues = {}, submitLabel = 'Save Draft', onSubmit, children }) {
  const [values, setValues] = useState(() => fields.reduce((acc, field) => ({ ...acc, [field.name]: initialValues[field.name] || '' }), {}));
  const [errors, setErrors] = useState({});
  const [message, setMessage] = useState('');

  const handleChange = (event) => {
    const { name, value } = event.target;
    setValues((current) => ({ ...current, [name]: value }));
    setErrors((current) => ({ ...current, [name]: '' }));
  };

  const requiredFields = useMemo(() => fields.filter((field) => field.required), [fields]);

  const handleSubmit = (event) => {
    event.preventDefault();
    const nextErrors = validateRequired(values, requiredFields);
    setErrors(nextErrors);
    if (Object.keys(nextErrors).length === 0) {
      onSubmit?.(values);
      setMessage(`${submitLabel} completed.`);
    }
  };

  return (
    <form className="ems-form" onSubmit={handleSubmit}>
      {message && <div className="ems-action-message">{message}</div>}
      <div className="ems-form-grid">
        {fields.map((field) => (
          <div key={field.name}>
            <FormField {...field} value={values[field.name]} onChange={handleChange} />
            {errors[field.name] && <small className="ems-form-error">{errors[field.name]}</small>}
          </div>
        ))}
      </div>
      {children}
      <button className="ems-btn ems-btn-primary" type="submit"><Icon name="checkCircle" size={16} /> {submitLabel}</button>
    </form>
  );
}

