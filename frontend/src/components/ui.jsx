export function ApprovalWorkflow({ title = 'Approval Workflow', dsc = false }) {
  const steps = ['Draft', 'Submitted', 'Verified', 'Approved'];
  const [status, setStatus] = useState('Submitted');

  return (
    <div className="ems-approval">
      <div className="ems-approval-title">
        <strong>{title}</strong>
        {dsc && <span><Icon name="shield" size={14} /> DSC required</span>}
      </div>
      <div className="ems-workflow-line">
        {steps.map((step, index) => (
          <div key={step} className="ems-workflow-step">
            <span>{index + 1}</span>
            <strong>{step}</strong>
          </div>
        ))}
      </div>
      <div className="ems-action-row">
        <button className="ems-btn ems-btn-primary" type="button" onClick={() => setStatus('Verified')}>Verify</button>
        <button className="ems-btn ems-btn-secondary" type="button" onClick={() => setStatus('Sent Back')}>Send Back</button>
        <button className="ems-btn ems-btn-danger" type="button" onClick={() => setStatus('Rejected')}>Reject</button>
      </div>
      <div className="ems-action-message">Workflow status: {status}</div>
    </div>
  );
}

export function FilterBar({ filters }) {
  const [values, setValues] = useState(() => filters.reduce((acc, filter) => ({ ...acc, [filter.name]: '' }), {}));
  const [message, setMessage] = useState('');

  const handleChange = (event) => {
    const { name, value } = event.target;
    setValues((current) => ({ ...current, [name]: value }));
  };

  return (
    <div className="ems-filter-bar">
      {filters.map((filter) => (
        <FormField key={filter.name} {...filter} value={values[filter.name]} onChange={handleChange} />
      ))}
      <button className="ems-btn ems-btn-primary" type="button" onClick={() => setMessage('Filters applied to report preview.')}><Icon name="filter" size={15} /> Apply Filters</button>
      {message && <div className="ems-action-message">{message}</div>}
    </div>
  );
}

